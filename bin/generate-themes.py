#!/usr/bin/env python3
"""Generate ThemeDefinitions.h from resources/themes/*.yaml.

Usage:
    python3 bin/generate-themes.py <output_header_path> [themes_dir]

Reads all .yaml files from the themes directory (default: resources/themes/),
applies the Base16-to-QPalette mapping, and writes a C++ header containing
a registry of all theme definitions.

Themes with an `overrides:` section use those exact color values for QPalette
roles instead of the automatic Base16 mapping. This is how our custom themes
(Komai, Nheko) preserve their exact colors.
"""

import os
import re
import sys
from pathlib import Path


def parse_yaml(path: str) -> dict:
    """Minimal YAML parser for Base16 theme files.

    Handles the flat structure of Base16 YAML: top-level scalars and one
    level of nested mapping (palette:, overrides:). No external dependency.
    """
    result = {}
    current_section = None

    with open(path) as f:
        for line in f:
            line = line.rstrip()
            if not line or line.startswith("#"):
                continue

            # Nested key (2-space indent)
            if line.startswith("  "):
                if current_section is None:
                    continue
                m = re.match(r'  (\w+):\s*"?([^"#]*)"?\s*(?:#.*)?$', line)
                if m:
                    result[current_section][m.group(1)] = m.group(2).strip().strip('"')
                continue

            # Top-level key
            m = re.match(r'(\w+):\s*"?([^"#]*)"?\s*(?:#.*)?$', line)
            if m:
                key = m.group(1)
                value = m.group(2).strip().strip('"')
                if value:
                    result[key] = value
                    current_section = None
                else:
                    # Section header (e.g., "palette:" or "overrides:")
                    result[key] = {}
                    current_section = key

    return result


def parse_color(hex_str: str) -> tuple:
    """Parse a hex color string (with or without #) to (r, g, b) ints."""
    h = hex_str.lstrip("#").strip()
    if len(h) != 6:
        raise ValueError(f"Invalid hex color: {hex_str!r}")
    return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))


def hex_to_qcolor(hex_str: str) -> str:
    """Convert hex string to QColor constructor."""
    r, g, b = parse_color(hex_str)
    return f"QColor(0x{r:02x}, 0x{g:02x}, 0x{b:02x})"


def base16_to_palette(palette: dict, variant: str, overrides: dict | None) -> dict:
    """Map Base16 slots to QPalette role colors.

    If overrides dict is provided, those QPalette roles use the override
    values instead of the automatic mapping.
    """
    # Automatic Base16 mapping
    mapping = {
        "window": palette["base00"],
        "windowText": palette["base05"],
        "base": palette.get("base01", palette["base00"]),
        "alternateBase": palette.get(
            "base02", palette.get("base01", palette["base00"])
        ),
        "text": palette["base05"],
        "brightText": palette.get("base07", palette.get("base06", palette["base05"])),
        "button": palette.get("base01", palette["base00"]),
        "buttonText": palette.get("base04", palette.get("base03", palette["base05"])),
        "light": palette.get("base06", palette.get("base05", "ffffff")),
        "mid": palette.get("base03", palette.get("base02", palette["base01"])),
        "dark": palette.get("base01", palette["base00"]),
        "highlight": palette.get("base0D", "38a3d8"),
        "highlightedText": palette.get("base07", "ffffff")
        if variant == "dark"
        else palette.get("base00", "ffffff"),
        "link": palette.get("base0D", "38a3d8"),
        "toolTipBase": palette.get("base01", palette["base00"]),
        "toolTipText": palette["base05"],
    }

    # Apply overrides
    if overrides:
        for key, value in overrides.items():
            if key in mapping:
                mapping[key] = value

    return mapping


def base16_to_custom(palette: dict, overrides: dict | None) -> dict:
    """Map Base16 slots to Theme custom color properties."""
    custom = {
        "red": palette.get("base08", "a82353"),
        "green": palette.get("base0B", "008000"),
        "orange": palette.get("base09", "fcbe05"),
        "error": palette.get("base08", "dd3d3d"),
    }

    # Override custom properties if specified
    if overrides:
        for key in ("red", "green", "orange", "error"):
            if key in overrides:
                custom[key] = overrides[key]

    return custom


def generate_header(themes: list[dict]) -> str:
    """Generate the C++ header content."""
    lines = []
    lines.append("// Auto-generated by bin/generate-themes.py — DO NOT EDIT")
    lines.append("// Re-generate with: python3 bin/generate-themes.py <output>")
    lines.append("")
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <QColor>")
    lines.append("#include <QPalette>")
    lines.append("#include <QString>")
    lines.append("#include <QStringList>")
    lines.append("#include <vector>")
    lines.append("")
    lines.append("struct ThemeDef {")
    lines.append("    QString slug;")
    lines.append("    QString name;")
    lines.append('    QString variant;  // "light" or "dark"')
    lines.append("    int sortOrder;")
    lines.append("")
    lines.append("    // QPalette colors")
    lines.append(
        "    QColor window, windowText, base, alternateBase, text, brightText;"
    )
    lines.append("    QColor button, buttonText, light, mid, dark;")
    lines.append("    QColor highlight, highlightedText, link;")
    lines.append("    QColor toolTipBase, toolTipText;")
    lines.append("")
    lines.append("    // Custom Theme properties")
    lines.append("    QColor red, green, orange, error;")
    lines.append("")
    lines.append("    QPalette toPalette() const {")
    lines.append(
        "        QPalette p(windowText, button, light, dark, mid, text, brightText, base, window);"
    )
    lines.append("        p.setColor(QPalette::AlternateBase, alternateBase);")
    lines.append("        p.setColor(QPalette::Highlight, highlight);")
    lines.append("        p.setColor(QPalette::HighlightedText, highlightedText);")
    lines.append("        p.setColor(QPalette::ToolTipBase, toolTipBase);")
    lines.append("        p.setColor(QPalette::ToolTipText, toolTipText);")
    lines.append("        p.setColor(QPalette::Link, link);")
    lines.append("        p.setColor(QPalette::ButtonText, buttonText);")
    lines.append("        return p;")
    lines.append("    }")
    lines.append("};")
    lines.append("")
    lines.append("inline const std::vector<ThemeDef>& themeDefinitions() {")
    lines.append("    static const std::vector<ThemeDef> themes = {")

    for i, t in enumerate(themes):
        pal = t["palette_mapped"]
        custom = t["custom"]
        slug = t["slug"]
        name = t["name"]
        variant = t["variant"]
        order = t["sort_order"]

        lines.append(f"        ThemeDef{{")
        lines.append(f'            QStringLiteral("{slug}"),')
        lines.append(f'            QStringLiteral("{name}"),')
        lines.append(f'            QStringLiteral("{variant}"),')
        lines.append(f"            {order},")
        lines.append(f"            // QPalette colors")
        lines.append(f"            /*window*/ {hex_to_qcolor(pal['window'])},")
        lines.append(f"            /*windowText*/ {hex_to_qcolor(pal['windowText'])},")
        lines.append(f"            /*base*/ {hex_to_qcolor(pal['base'])},")
        lines.append(
            f"            /*alternateBase*/ {hex_to_qcolor(pal['alternateBase'])},"
        )
        lines.append(f"            /*text*/ {hex_to_qcolor(pal['text'])},")
        lines.append(f"            /*brightText*/ {hex_to_qcolor(pal['brightText'])},")
        lines.append(f"            /*button*/ {hex_to_qcolor(pal['button'])},")
        lines.append(f"            /*buttonText*/ {hex_to_qcolor(pal['buttonText'])},")
        lines.append(f"            /*light*/ {hex_to_qcolor(pal['light'])},")
        lines.append(f"            /*mid*/ {hex_to_qcolor(pal['mid'])},")
        lines.append(f"            /*dark*/ {hex_to_qcolor(pal['dark'])},")
        lines.append(f"            /*highlight*/ {hex_to_qcolor(pal['highlight'])},")
        lines.append(
            f"            /*highlightedText*/ {hex_to_qcolor(pal['highlightedText'])},"
        )
        lines.append(f"            /*link*/ {hex_to_qcolor(pal['link'])},")
        lines.append(
            f"            /*toolTipBase*/ {hex_to_qcolor(pal['toolTipBase'])},"
        )
        lines.append(
            f"            /*toolTipText*/ {hex_to_qcolor(pal['toolTipText'])},"
        )
        lines.append(f"            // Custom properties")
        lines.append(f"            /*red*/ {hex_to_qcolor(custom['red'])},")
        lines.append(f"            /*green*/ {hex_to_qcolor(custom['green'])},")
        lines.append(f"            /*orange*/ {hex_to_qcolor(custom['orange'])},")
        lines.append(f"            /*error*/ {hex_to_qcolor(custom['error'])},")
        lines.append(f"        }},")

    lines.append("    };")
    lines.append("    return themes;")
    lines.append("}")
    lines.append("")
    lines.append("inline const ThemeDef* findTheme(QStringView slug) {")
    lines.append("    for (const auto& t : themeDefinitions()) {")
    lines.append("        if (t.slug == slug) return &t;")
    lines.append("    }")
    lines.append("    return nullptr;")
    lines.append("}")
    lines.append("")
    lines.append("inline QStringList themeNames(const QString& variant = QString()) {")
    lines.append("    QStringList names;")
    lines.append("    for (const auto& t : themeDefinitions()) {")
    lines.append("        if (variant.isEmpty() || t.variant == variant)")
    lines.append("            names.append(t.name);")
    lines.append("    }")
    lines.append("    return names;")
    lines.append("}")
    lines.append("")
    lines.append("inline QStringList themeSlugs(const QString& variant = QString()) {")
    lines.append("    QStringList slugs;")
    lines.append("    for (const auto& t : themeDefinitions()) {")
    lines.append("        if (variant.isEmpty() || t.variant == variant)")
    lines.append("            slugs.append(t.slug);")
    lines.append("    }")
    lines.append("    return slugs;")
    lines.append("}")
    lines.append("")
    lines.append("inline QString themeVariant(QStringView slug) {")
    lines.append('    if (slug == u"system") return QStringLiteral("system");')
    lines.append("    const auto *def = findTheme(slug);")
    lines.append('    return def ? def->variant : QStringLiteral("light");')
    lines.append("}")
    lines.append("")
    lines.append("inline QString defaultThemeSlug(QStringView variant) {")
    lines.append('    if (variant == u"system") return QStringLiteral("system");')
    lines.append("    for (const auto& t : themeDefinitions()) {")
    lines.append("        if (t.variant == variant) return t.slug;")
    lines.append("    }")
    lines.append('    return QStringLiteral("komai");')
    lines.append("}")
    lines.append("")

    return "\n".join(lines) + "\n"


def main():
    if len(sys.argv) < 2:
        print(
            f"Usage: {sys.argv[0]} <output_header_path> [themes_dir]", file=sys.stderr
        )
        sys.exit(1)

    output_path = sys.argv[1]
    themes_dir = sys.argv[2] if len(sys.argv) > 2 else "resources/themes"

    # Find all YAML theme files
    theme_files = sorted(Path(themes_dir).glob("*.yaml"))
    if not theme_files:
        print(f"ERROR: No .yaml files found in {themes_dir}", file=sys.stderr)
        sys.exit(1)

    # Sort order: komai themes first (0-99), nheko themes (100-199), others alphabetically (200+)
    def sort_key(slug: str) -> int:
        if slug == "komai":
            return 0
        elif slug == "komai-dark":
            return 1
        elif slug.startswith("nheko"):
            return 100 + ord(slug[-1]) if slug else 100
        else:
            return 200

    themes = []
    for tf in theme_files:
        data = parse_yaml(str(tf))
        slug = tf.stem  # filename without extension

        # Validate required fields
        for field in ("name", "variant", "palette"):
            if field not in data:
                print(f"ERROR: {tf} missing required field: {field}", file=sys.stderr)
                sys.exit(1)

        if data["variant"] not in ("light", "dark"):
            print(
                f"ERROR: {tf} variant must be 'light' or 'dark', got: {data['variant']}",
                file=sys.stderr,
            )
            sys.exit(1)

        palette = data["palette"]
        for slot in (f"base{i:02X}" for i in range(16)):
            if slot not in palette:
                print(f"ERROR: {tf} missing palette slot: {slot}", file=sys.stderr)
                sys.exit(1)

        overrides = data.get("overrides")

        palette_mapped = base16_to_palette(palette, data["variant"], overrides)
        custom = base16_to_custom(palette, overrides)

        themes.append(
            {
                "slug": slug,
                "name": data["name"],
                "variant": data["variant"],
                "sort_order": sort_key(slug),
                "palette_mapped": palette_mapped,
                "custom": custom,
            }
        )

    # Sort by sort_order, then by name
    themes.sort(key=lambda t: (t["sort_order"], t["name"]))

    # Generate and write
    header = generate_header(themes)

    os.makedirs(os.path.dirname(output_path) or ".", exist_ok=True)
    with open(output_path, "w") as f:
        f.write(header)

    print(f"Generated {output_path} with {len(themes)} themes:")
    for t in themes:
        print(f"  {t['slug']:30s} {t['variant']:5s}  {t['name']}")


if __name__ == "__main__":
    main()
