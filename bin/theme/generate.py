#!/usr/bin/env python3
"""Generate ThemeDefinitions.h from resources/themes/*.yml.

Usage:
    python3 bin/theme/generate.py <output_header_path> [themes_dir]

Reads all .yml files from the themes directory (default: resources/themes/)
and writes a C++ header containing a registry of all theme definitions.
Each YAML file contains resolved QPalette-level colors directly.
"""

import os
import sys
from pathlib import Path

from colors import (
    parse_yaml,
    parse_color,
    hex_to_qcolor,
    contrast_ratio,
    luminance,
    ALL_PALETTE_KEYS,
    PALETTE_KEYS,
    CUSTOM_KEYS,
)


def generate_header(themes: list[dict]) -> str:
    """Generate the C++ header content."""
    lines = []
    lines.append("// Auto-generated by bin/theme/generate.py — DO NOT EDIT")
    lines.append("// Re-generate with: python3 bin/theme/generate.py <output>")
    lines.append("")
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <QColor>")
    lines.append("#include <QPalette>")
    lines.append("#include <QString>")
    lines.append("#include <QStringList>")
    lines.append("#include <vector>")
    lines.append("")
    lines.append("struct ThemeDef {")
    lines.append("    QString slug;")
    lines.append("    QString name;")
    lines.append('    QString variant;  // "light" or "dark"')
    lines.append("    int sortOrder;")
    lines.append("")
    lines.append("    // QPalette colors")
    lines.append(
        "    QColor window, windowText, base, alternateBase, text, brightText;"
    )
    lines.append("    QColor button, buttonText, light, mid, dark;")
    lines.append("    QColor highlight, highlightedText, link;")
    lines.append("    QColor toolTipBase, toolTipText;")
    lines.append("")
    lines.append("    // Semantic accent colors")
    lines.append("    QColor attention, success, warning, error;")
    lines.append("")
    lines.append("    // User colors for sender/member color coding")
    lines.append("    QColor userColorSelf;")
    lines.append("    std::vector<QColor> userColorOthers;")
    lines.append("")
    lines.append('    QString source;  // "builtin" or "/full/path/to/theme.yml"')
    lines.append("")
    lines.append("    QPalette toPalette() const {")
    lines.append(
        "        QPalette p(windowText, button, light, dark, mid, text, brightText, base, window);"
    )
    lines.append("        p.setColor(QPalette::AlternateBase, alternateBase);")
    lines.append("        p.setColor(QPalette::Highlight, highlight);")
    lines.append("        p.setColor(QPalette::HighlightedText, highlightedText);")
    lines.append("        p.setColor(QPalette::ToolTipBase, toolTipBase);")
    lines.append("        p.setColor(QPalette::ToolTipText, toolTipText);")
    lines.append("        p.setColor(QPalette::Link, link);")
    lines.append("        p.setColor(QPalette::ButtonText, buttonText);")
    lines.append("        return p;")
    lines.append("    }")
    lines.append("};")
    lines.append("")
    lines.append("inline const std::vector<ThemeDef>& themeDefinitions() {")
    lines.append("    static const std::vector<ThemeDef> themes = {")

    for i, t in enumerate(themes):
        pal = t["palette_mapped"]
        custom = t["custom"]
        slug = t["slug"]
        name = t["name"]
        variant = t["variant"]
        order = t["sort_order"]
        user_self = t["user_color_self"]
        user_others = t["user_color_others"]

        lines.append(f"        ThemeDef{{")
        lines.append(f'            QStringLiteral("{slug}"),')
        lines.append(f'            QStringLiteral("{name}"),')
        lines.append(f'            QStringLiteral("{variant}"),')
        lines.append(f"            {order},")
        lines.append(f"            // QPalette colors")
        lines.append(f"            /*window*/ {hex_to_qcolor(pal['window'])},")
        lines.append(f"            /*windowText*/ {hex_to_qcolor(pal['windowText'])},")
        lines.append(f"            /*base*/ {hex_to_qcolor(pal['base'])},")
        lines.append(
            f"            /*alternateBase*/ {hex_to_qcolor(pal['alternateBase'])},"
        )
        lines.append(f"            /*text*/ {hex_to_qcolor(pal['text'])},")
        lines.append(f"            /*brightText*/ {hex_to_qcolor(pal['brightText'])},")
        lines.append(f"            /*button*/ {hex_to_qcolor(pal['button'])},")
        lines.append(f"            /*buttonText*/ {hex_to_qcolor(pal['buttonText'])},")
        lines.append(f"            /*light*/ {hex_to_qcolor(pal['light'])},")
        lines.append(f"            /*mid*/ {hex_to_qcolor(pal['mid'])},")
        lines.append(f"            /*dark*/ {hex_to_qcolor(pal['dark'])},")
        lines.append(f"            /*highlight*/ {hex_to_qcolor(pal['highlight'])},")
        lines.append(
            f"            /*highlightedText*/ {hex_to_qcolor(pal['highlightedText'])},"
        )
        lines.append(f"            /*link*/ {hex_to_qcolor(pal['link'])},")
        lines.append(
            f"            /*toolTipBase*/ {hex_to_qcolor(pal['toolTipBase'])},"
        )
        lines.append(
            f"            /*toolTipText*/ {hex_to_qcolor(pal['toolTipText'])},"
        )
        lines.append(f"            // Semantic accent colors")
        lines.append(f"            /*attention*/ {hex_to_qcolor(custom['attention'])},")
        lines.append(f"            /*success*/ {hex_to_qcolor(custom['success'])},")
        lines.append(f"            /*warning*/ {hex_to_qcolor(custom['warning'])},")
        lines.append(f"            /*error*/ {hex_to_qcolor(custom['error'])},")
        lines.append(f"            // User colors")
        lines.append(f"            /*userColorSelf*/ {hex_to_qcolor(user_self)},")

        others_items = ", ".join(hex_to_qcolor(c) for c in user_others)
        lines.append(f"            /*userColorOthers*/ {{{others_items}}},")

        lines.append(f'            QStringLiteral("builtin"),')
        lines.append(f"        }},")

    lines.append("    };")
    lines.append("    return themes;")
    lines.append("}")
    lines.append("")
    lines.append("inline const ThemeDef* findTheme(QStringView slug) {")
    lines.append("    for (const auto& t : themeDefinitions()) {")
    lines.append("        if (t.slug == slug) return &t;")
    lines.append("    }")
    lines.append("    return nullptr;")
    lines.append("}")
    lines.append("")
    lines.append("inline QStringList themeNames(const QString& variant = QString()) {")
    lines.append("    QStringList names;")
    lines.append("    for (const auto& t : themeDefinitions()) {")
    lines.append("        if (variant.isEmpty() || t.variant == variant)")
    lines.append("            names.append(t.name);")
    lines.append("    }")
    lines.append("    return names;")
    lines.append("}")
    lines.append("")
    lines.append("inline QStringList themeSlugs(const QString& variant = QString()) {")
    lines.append("    QStringList slugs;")
    lines.append("    for (const auto& t : themeDefinitions()) {")
    lines.append("        if (variant.isEmpty() || t.variant == variant)")
    lines.append("            slugs.append(t.slug);")
    lines.append("    }")
    lines.append("    return slugs;")
    lines.append("}")
    lines.append("")
    lines.append("inline QString themeVariant(QStringView slug) {")
    lines.append('    if (slug == u"system") return QStringLiteral("system");')
    lines.append("    const auto *def = findTheme(slug);")
    lines.append('    return def ? def->variant : QStringLiteral("light");')
    lines.append("}")
    lines.append("")
    lines.append("inline QString defaultThemeSlug(QStringView variant) {")
    lines.append('    if (variant == u"system") return QStringLiteral("system");')
    lines.append("    for (const auto& t : themeDefinitions()) {")
    lines.append("        if (t.variant == variant) return t.slug;")
    lines.append("    }")
    lines.append('    return QStringLiteral("komai-light");')
    lines.append("}")
    lines.append("")

    return "\n".join(lines) + "\n"


def main():
    if len(sys.argv) < 2:
        print(
            f"Usage: {sys.argv[0]} <output_header_path> [themes_dir]", file=sys.stderr
        )
        sys.exit(1)

    output_path = sys.argv[1]
    themes_dir = sys.argv[2] if len(sys.argv) > 2 else "resources/themes"

    # Find all YAML theme files
    theme_files = sorted(Path(themes_dir).glob("*.yml"))
    if not theme_files:
        print(f"ERROR: No .yml files found in {themes_dir}", file=sys.stderr)
        sys.exit(1)

    # Sort order: komai themes first (0-99), nheko themes (100-199), others alphabetically (200+)
    def sort_key(slug: str) -> int:
        if slug == "komai-light":
            return 0
        elif slug == "komai-dark":
            return 1
        elif slug.startswith("nheko"):
            return 100 + ord(slug[-1]) if slug else 100
        else:
            return 200

    themes = []
    for tf in theme_files:
        data = parse_yaml(str(tf))
        slug = tf.stem  # filename without extension

        # Validate required fields
        for field in ("name", "variant", "palette", "userColors"):
            if field not in data:
                print(f"ERROR: {tf} missing required field: {field}", file=sys.stderr)
                sys.exit(1)

        if data["variant"] not in ("light", "dark"):
            print(
                f"ERROR: {tf} variant must be 'light' or 'dark', got: {data['variant']}",
                file=sys.stderr,
            )
            sys.exit(1)

        palette = data["palette"]

        # Validate all 20 palette keys exist
        for key in ALL_PALETTE_KEYS:
            if key not in palette:
                print(f"ERROR: {tf} missing palette key: {key}", file=sys.stderr)
                sys.exit(1)

        # Validate userColors
        user_colors = data["userColors"]
        if "self" not in user_colors:
            print(f"ERROR: {tf} missing userColors.self", file=sys.stderr)
            sys.exit(1)
        if "others" not in user_colors or not isinstance(user_colors["others"], list):
            print(f"ERROR: {tf} missing or invalid userColors.others", file=sys.stderr)
            sys.exit(1)
        if len(user_colors["others"]) < 1:
            print(f"ERROR: {tf} userColors.others must have at least 1 entry", file=sys.stderr)
            sys.exit(1)

        # Read QPalette colors directly
        palette_mapped = {key: palette[key] for key in PALETTE_KEYS}
        custom = {key: palette[key] for key in CUSTOM_KEYS}

        themes.append(
            {
                "slug": slug,
                "name": data["name"],
                "variant": data["variant"],
                "sort_order": sort_key(slug),
                "palette_mapped": palette_mapped,
                "custom": custom,
                "user_color_self": user_colors["self"],
                "user_color_others": user_colors["others"],
            }
        )

    # Sort by sort_order, then by name
    themes.sort(key=lambda t: (t["sort_order"], t["name"]))

    # Generate and write
    header = generate_header(themes)

    os.makedirs(os.path.dirname(output_path) or ".", exist_ok=True)
    with open(output_path, "w") as f:
        f.write(header)

    print(f"Generated {output_path} with {len(themes)} themes:")
    for t in themes:
        pal = t["palette_mapped"]
        cr_ht = contrast_ratio(pal["highlightedText"], pal["highlight"])
        cr_hw = contrast_ratio(pal["highlight"], pal["window"])
        cr_bt = contrast_ratio(pal["brightText"], pal["dark"])
        cr_dw = contrast_ratio(pal["dark"], pal["window"])
        n_others = len(t["user_color_others"])
        print(f"  {t['slug']:25s} {t['variant']:5s}  {t['name']}  (userColors: {n_others} others)")
        print(f"    hlText/hl={cr_ht:.1f}  hl/win={cr_hw:.1f}  "
              f"brightText/dark={cr_bt:.1f}  dark/win={cr_dw:.1f}")


if __name__ == "__main__":
    main()
