"""Generate docs/architecture/icons-list.md from resources/res.qrc."""

from __future__ import annotations

import argparse
import sys
import urllib.parse
import xml.etree.ElementTree as ET
from pathlib import Path


def build_markdown(repo_root: Path) -> str:
    qrc_path = repo_root / "resources" / "res.qrc"
    tree = ET.parse(qrc_path)
    root = tree.getroot()

    entries: list[tuple[str, str, Path, bool]] = []
    for qresource in root.findall("qresource"):
        if qresource.attrib.get("prefix") != "/icons":
            continue

        for file_node in qresource.findall("file"):
            source = (file_node.text or "").strip()
            if not source.endswith(".svg"):
                continue
            if not source.startswith("icons/"):
                continue

            alias = (file_node.attrib.get("alias") or source).strip()
            if not alias.startswith("icons/"):
                continue

            fs_rel = Path("resources") / Path(source)
            exists = (repo_root / fs_rel).is_file()
            entries.append((source, alias, fs_rel, exists))

    entries.sort(key=lambda item: item[0])

    lines = [
        "<!-- AUTO-GENERATED by bin/icons/generate-list.py. Do not edit manually. -->",
        "# Icon Catalog",
        "",
        "Generated from `resources/res.qrc`, sorted by icon source path.",
        "",
        "🛠️ Regenerate with `just icons-generate-list`.",
        "",
        "| Icon | Alias |",
        "| --- | --- |",
    ]

    for source, alias, fs_rel, exists in entries:
        rel_from_doc = Path("..") / ".." / fs_rel
        encoded_path = urllib.parse.quote(rel_from_doc.as_posix(), safe="/-._~")
        if exists:
            icon_cell = f"![{source}]({encoded_path})<br>`{source}`"
        else:
            icon_cell = f"`{source}` (missing)"
        lines.append(f"| {icon_cell} | `{alias}` |")

    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate docs/architecture/icons-list.md from resources/res.qrc."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail if docs/architecture/icons-list.md is not up to date.",
    )
    args = parser.parse_args()

    repo_root = Path(__file__).resolve().parents[2]
    output_path = repo_root / "docs" / "architecture" / "icons-list.md"
    expected = build_markdown(repo_root)

    if args.check:
        current = output_path.read_text(encoding="utf-8") if output_path.exists() else ""
        if current != expected:
            print(
                "icons-list.md is out of date. Run `just icons-generate-list`.",
                file=sys.stderr,
            )
            return 1
        return 0

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(expected, encoding="utf-8")
    print(f"Wrote {output_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
