set -euo pipefail

usage() {
    cat <<'USAGE'
Usage:
  settings-3-layer-mapping.sh [generate|check] [--output PATH]
  settings-3-layer-mapping.sh --check [--output PATH]

Description:
  Generates a settings mapping report:
  SettingId <-> runtime getter expression <-> SettingKey const <-> dotted key

Options:
  --output PATH  Output file path
                 (default: docs/architecture/settings/3-layer-mapping.md)
  --check        Backward-compatible alias for 'check' mode.
  -h, --help     Show this help.

Notes:
  The default report target is tracked in git.
USAGE
}

script_dir="$(cd "$(dirname "$0")" && pwd)"
repo_root="$(cd "$script_dir/../.." && pwd)"
output_path="$repo_root/docs/architecture/settings/3-layer-mapping.md"
check_mode=0

if [[ $# -gt 0 ]]; then
    case "$1" in
        generate)
            shift
            ;;
        check)
            check_mode=1
            shift
            ;;
    esac
fi

while [[ $# -gt 0 ]]; do
    case "$1" in
        --check)
            check_mode=1
            shift
            ;;
        --output)
            [[ $# -ge 2 ]] || { echo "error: --output requires a path" >&2; exit 2; }
            output_path="$2"
            shift 2
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            # Backward-compatible positional output path.
            output_path="$1"
            shift
            ;;
    esac
done

tmpdir="$(mktemp -d /tmp/komai-settings-map.XXXXXX)"
trap 'rm -rf "$tmpdir"' EXIT

generated_path="$output_path"
if [[ "$check_mode" -eq 1 ]]; then
    generated_path="$tmpdir/settings-3-layer-mapping.generated.md"
fi

# SettingId -> SettingKey const (from sectioned persisted definition fragments)
awk '
  /SettingId::/ { if (match($0, /SettingId::([A-Za-z0-9_]+)/, m)) sid=m[1]; }
  /SettingKey::/ {
    if (sid != "" && match($0, /SettingKey::([A-Za-z0-9_]+)/, m)) {
      print sid "\t" m[1];
      sid="";
    }
  }
' "$repo_root"/src/settings/core/SettingsDefinitionsPersisted*.inc | sort -u > "$tmpdir/id_to_keyconst.tsv"

# SettingKey const -> dotted persisted key (supports multiline constant definitions)
awk '
  BEGIN {name=""}
  match($0, /^constexpr auto ([A-Za-z0-9_]+)[[:space:]]*=/, m) { name=m[1] }
  {
    if (name != "" && match($0, /"([^"]+)";/, q)) {
      print name "\t" q[1];
      name="";
    }
  }
' "$repo_root"/src/settings/SettingKeys.h | sort -u > "$tmpdir/keyconst_to_dotted.tsv"

# SettingId -> runtime getter expression (supports multiline X(...) macro invocations)
awk '
  BEGIN {acc=""; collecting=0}
  {
    line=$0
    if (!collecting && line ~ /^X\(/) {
      collecting=1
      acc=line
      if (line ~ /\)$/) {
        collecting=0
        if (match(acc, /^X\(([A-Za-z0-9_]+),[[:space:]]*(.*)\)$/, m))
          print m[1] "\t" m[2]
      }
      next
    }
    if (collecting) {
      sub(/^[[:space:]]+/, "", line)
      acc=acc line
      if (line ~ /\)$/) {
        collecting=0
        if (match(acc, /^X\(([A-Za-z0-9_]+),[[:space:]]*(.*)\)$/, m))
          print m[1] "\t" m[2]
      }
    }
  }
' "$repo_root"/src/settings/ui/facade/UserSettingsCoreStoreBridgeEntries*.inc | sort -u > "$tmpdir/id_to_runtimeexpr.tsv"

join -t $'\t' -1 1 -2 1 "$tmpdir/id_to_keyconst.tsv" "$tmpdir/id_to_runtimeexpr.tsv" > "$tmpdir/id_keyconst_runtime.tsv"
join -t $'\t' -1 2 -2 1 <(sort -t $'\t' -k2,2 "$tmpdir/id_keyconst_runtime.tsv") "$tmpdir/keyconst_to_dotted.tsv" > "$tmpdir/full.tsv"
awk -F '\t' '{print $2"\t"$1"\t"$3"\t"$4}' "$tmpdir/full.tsv" | sort > "$tmpdir/full_sorted.tsv"

# Heuristic naming audit:
# - expected runtime getter name is lcfirst(SettingId)
# - explicit '*PersistedValue' suffix is allowed for persistence adapters
: > "$tmpdir/name_mismatches.tsv"
: > "$tmpdir/name_exceptions.tsv"
awk -F '\t' -v exceptionsFile="$tmpdir/name_exceptions.tsv" -v mismatchesFile="$tmpdir/name_mismatches.tsv" '
  function lcfirst(s) { return tolower(substr(s, 1, 1)) substr(s, 2) }
  {
    id=$1
    expr=$3
    getter=""
    if (match(expr, /settings\.([A-Za-z0-9_]+)\(/, m)) getter=m[1]
    expected=lcfirst(id)
    if (getter != "" && getter == expected "PersistedValue") {
      print id "\t" expected "\t" getter "\t" expr > exceptionsFile
      next
    }
    if (getter != "" && getter != expected)
      print id "\t" expected "\t" getter "\t" expr > mismatchesFile
  }
' "$tmpdir/full_sorted.tsv"

rows="$(wc -l < "$tmpdir/full_sorted.tsv")"
mismatches="$(wc -l < "$tmpdir/name_mismatches.tsv")"
exceptions="$(wc -l < "$tmpdir/name_exceptions.tsv")"

mkdir -p "$(dirname "$generated_path")"
{
  echo "# Settings 3-Layer Mapping"
  echo
  echo "Generated by: \`bin/settings/settings-3-layer-mapping.sh\`"
  echo
  echo "> Update command: \`just settings-3-layer-mapping-generate\`"
  echo
  echo "Generated from:"
  echo "- \`src/settings/core/SettingsDefinitionsPersisted*.inc\`"
  echo "- \`src/settings/ui/facade/UserSettingsCoreStoreBridgeEntries*.inc\`"
  echo "- \`src/settings/SettingKeys.h\`"
  echo
  echo "Rows: $rows"
  echo
  echo "Naming mismatch summary:"
  echo "- Total hard mismatches (heuristic \`lcfirst(SettingId)\` vs runtime getter name): $mismatches"
  echo "- Allowed exceptions (\`*PersistedValue\` suffix): $exceptions"
  if [[ "$exceptions" -gt 0 ]]; then
    while IFS=$'\t' read -r id expected getter expr; do
      echo "- exception \`$id\`: expected \`$expected\`, uses allowed \`$getter\` (from \`$expr\`)"
    done < "$tmpdir/name_exceptions.tsv"
  fi
  if [[ "$mismatches" -gt 0 ]]; then
    while IFS=$'\t' read -r id expected getter expr; do
      echo "- \`$id\`: expected \`$expected\`, found \`$getter\` (from \`$expr\`)"
    done < "$tmpdir/name_mismatches.tsv"
  fi
  echo
  echo "| SettingId | Runtime Getter Expression | SettingKey Const | Persisted Key |"
  echo "|---|---|---|---|"
  awk -F '\t' '{printf("| `%s` | `%s` | `%s` | `%s` |\n", $1, $3, $2, $4)}' "$tmpdir/full_sorted.tsv"
} > "$generated_path"

if [[ "$check_mode" -eq 1 ]]; then
    if [[ ! -f "$output_path" ]]; then
        echo "Drift detected: '$output_path' does not exist." >&2
        echo "Run: just settings-3-layer-mapping-generate" >&2
        exit 1
    fi

    if ! cmp -s "$output_path" "$generated_path"; then
        echo "Drift detected in '$output_path'." >&2
        diff -u "$output_path" "$generated_path" | sed -n '1,200p' >&2 || true
        echo "Run: just settings-3-layer-mapping-generate" >&2
        exit 1
    fi

    echo "Up to date: $output_path"
    echo "Rows: $rows"
    echo "Hard mismatches: $mismatches"
    exit 0
fi

echo "Generated: $generated_path"
echo "Rows: $rows"
echo "Hard mismatches: $mismatches"
