"""Generate derived local icons from vendored Fluent source icons."""

from __future__ import annotations

import argparse
import sys
import xml.etree.ElementTree as ET
from pathlib import Path
from xml.sax.saxutils import escape

CHECKMARK_SOURCE = Path(
    "resources/icons/fluent/assets/Checkmark/SVG/ic_fluent_checkmark_32_regular.svg"
)
DOUBLE_CHECK_DEST = Path("resources/icons/ui/double-checkmark.svg")

# Secondary checkmark transform: smaller and shifted to the lower-left.
# Keep a visible gap from the primary mark.
SECONDARY_TRANSFORM = "matrix(0.75 0 0 0.75 3 1)"


def local_name(tag: str) -> str:
    if "}" in tag:
        return tag.split("}", 1)[1]
    return tag


def attrs_to_xml(attrs: dict[str, str]) -> str:
    preferred = [
        "d",
        "fill",
        "fill-rule",
        "clip-rule",
        "stroke",
        "stroke-width",
        "stroke-linecap",
        "stroke-linejoin",
        "opacity",
        "transform",
    ]

    ordered_keys: list[str] = []
    for key in preferred:
        if key in attrs:
            ordered_keys.append(key)
    for key in sorted(attrs.keys()):
        if key not in ordered_keys:
            ordered_keys.append(key)

    pairs = []
    for key in ordered_keys:
        escaped_value = escape(attrs[key], {'"': "&quot;"})
        pairs.append(f'{key}="{escaped_value}"')
    return " ".join(pairs)


def build_svg_text(source_svg: Path) -> str:
    tree = ET.parse(source_svg)
    root = tree.getroot()

    width = root.attrib.get("width", "32")
    height = root.attrib.get("height", "32")
    view_box = root.attrib.get("viewBox", "0 0 32 32")

    path_attrs: list[dict[str, str]] = []
    for child in root:
        if local_name(child.tag) != "path":
            continue
        path_attrs.append(dict(child.attrib))

    if not path_attrs:
        raise RuntimeError(f"No <path> elements found in {source_svg}")

    lines = [
        "<!-- AUTO-GENERATED by bin/icons/generate-derived.py. Do not edit manually. -->",
        f'<svg width="{escape(width)}" height="{escape(height)}" viewBox="{escape(view_box)}" fill="none" xmlns="http://www.w3.org/2000/svg">',
        f'  <g transform="{SECONDARY_TRANSFORM}" opacity="0.9">',
    ]
    for attrs in path_attrs:
        lines.append(f"    <path {attrs_to_xml(attrs)}/>")
    lines.append("  </g>")
    for attrs in path_attrs:
        lines.append(f"  <path {attrs_to_xml(attrs)}/>")
    lines.append("</svg>")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate derived icons (currently: ui/double-checkmark.svg)."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail if generated output is out of date.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Report whether a rewrite would happen, without writing.",
    )
    args = parser.parse_args()

    repo_root = Path(__file__).resolve().parents[2]
    source_svg = repo_root / CHECKMARK_SOURCE
    dest_svg = repo_root / DOUBLE_CHECK_DEST

    if not source_svg.is_file():
        print(f"Missing source icon: {source_svg}", file=sys.stderr)
        return 1

    expected = build_svg_text(source_svg)
    current = dest_svg.read_text(encoding="utf-8") if dest_svg.exists() else ""
    up_to_date = current == expected

    if args.check:
        if not up_to_date:
            print(
                "Derived icon is out of date: resources/icons/ui/double-checkmark.svg",
                file=sys.stderr,
            )
            print("Run: just icons-generate-derived", file=sys.stderr)
            return 1
        return 0

    if args.dry_run:
        if up_to_date:
            print("Derived icons are up to date.")
        else:
            print(
                "Would regenerate: resources/icons/ui/double-checkmark.svg "
                "from resources/icons/fluent/assets/Checkmark/SVG/ic_fluent_checkmark_32_regular.svg"
            )
        return 0

    if up_to_date:
        print("Derived icons already up to date.")
        return 0

    dest_svg.parent.mkdir(parents=True, exist_ok=True)
    dest_svg.write_text(expected, encoding="utf-8")
    print("Regenerated: resources/icons/ui/double-checkmark.svg")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
